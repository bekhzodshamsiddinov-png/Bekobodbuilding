// Renders lib/demo/sadaf.ts into supabase/seed.sql so the database sample and
// the built-in fallback are always identical.  Run: pnpm seed:gen
import { writeFileSync } from "node:fs";
import { demoApartments, demoBuildings, demoProject } from "../lib/demo/sadaf.ts";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const lines: string[] = [
  "-- GENERATED by scripts/gen-seed.ts from lib/demo/sadaf.ts. Do not edit by hand.",
  "-- Sadaf Residence sample: 3 buildings (12/1, 12/2, 16/5), 4 layouts per floor.",
  "begin;",
  "",
  `insert into public.projects (id, slug, name, city, address, status, hero_media, usd_rate) values (${[
    demoProject.id, demoProject.slug, demoProject.name, demoProject.city, demoProject.address,
    demoProject.status, demoProject.hero_media, demoProject.usd_rate,
  ].map(q).join(", ")}) on conflict (id) do nothing;`,
  "",
  "insert into public.buildings (id, project_id, code, name, floors, entrances, first_residential_floor, facade_image, floor_bands, sort) values",
  demoBuildings
    .map((b) => `  (${[b.id, b.project_id, b.code, b.name, b.floors, b.entrances, b.first_residential_floor, b.facade_image, b.floor_bands, b.sort].map(q).join(", ")})`)
    .join(",\n") + "\non conflict (id) do nothing;",
  "",
  "insert into public.apartments (id, building_id, entrance, floor, number, slug, rooms, area_m2, price_uzs, price_usd, status, orientation, has_balcony) values",
  demoApartments
    .map((a) => `  (${[a.id, a.building_id, a.entrance, a.floor, a.number, a.slug, a.rooms, a.area_m2, a.price_uzs, a.price_usd, a.status, a.orientation, a.has_balcony].map(q).join(", ")})`)
    .join(",\n") + "\non conflict (id) do nothing;",
  "",
  "commit;",
  "",
];

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), lines.join("\n"));
console.log(`seed.sql: 1 project, ${demoBuildings.length} buildings, ${demoApartments.length} apartments`);
